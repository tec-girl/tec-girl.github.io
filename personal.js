  // ===== FORO (giscus / GitHub Discussions) =====
  var FORO = { repo: "tec-girl/tec-girl.github.io", repoId: "", category: "Foro", categoryId: "" };

  function renderForum(lang) {
    var box = document.getElementById('foro-box');
    if (!box || forumLoaded) return;
    if (!FORO.repoId || !FORO.categoryId) {
      var dict = I18N[lang];
      var msg = (dict && dict['fo.fallback']) || originals['fo.fallback'] ||
        '💬 El foro se está conectando… mientras tanto puedes comentar en ' +
        '<a href="https://github.com/tec-girl/tec-girl.github.io/discussions" target="_blank" rel="noopener">GitHub Discussions ↗</a>';
      box.innerHTML = '<p class="foro-loading">' + msg + '</p>';
      return;
    }
    var s = document.createElement('script');
    s.src = 'https://giscus.app/client.js';
    s.setAttribute('data-repo', FORO.repo);
    s.setAttribute('data-repo-id', FORO.repoId);
    s.setAttribute('data-category', FORO.category);
    s.setAttribute('data-category-id', FORO.categoryId);
    s.setAttribute('data-mapping', 'pathname');
    s.setAttribute('data-reactions-enabled', '1');
    s.setAttribute('data-theme', 'transparent_dark');
    s.setAttribute('data-lang', lang === 'zh' ? 'zh-CN' : lang);
    s.crossOrigin = 'anonymous';
    s.async = true;
    box.innerHTML = '';
    box.appendChild(s);
    forumLoaded = true;
  }

  function applyLang(lang) {
    curLang = lang;
    var dict = I18N[lang] || null;
    textEls.forEach(function (el) {
      var k = el.getAttribute('data-i18n');
      if (el.closest('#foro-box')) return; // el foro se renderiza aparte
      el.innerHTML = (dict && dict[k] != null) ? dict[k] : originals[k];
    });
    htmlEls.forEach(function (el) {
      var k = el.getAttribute('data-i18n-html');
      el.innerHTML = (dict && dict[k] != null) ? dict[k] : originals[k];
    });
    document.documentElement.lang = (lang === 'zh') ? 'zh-CN' : lang;
    document.querySelectorAll('.lang-switch button').forEach(function (b) {
      b.classList.toggle('active', b.getAttribute('data-lang') === lang);
    });
    try { localStorage.setItem('tecgirl-lang', lang); } catch (e) {}
    renderForum(lang);
  }

  document.querySelectorAll('.lang-switch button').forEach(function (b) {
    b.addEventListener('click', function () { applyLang(b.getAttribute('data-lang')); });
  });

  var saved = null;
  try { saved = localStorage.getItem('tecgirl-lang'); } catch (e) {}
  if (saved && saved !== 'es') applyLang(saved); else renderForum('es');
